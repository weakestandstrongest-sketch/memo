/**
 * Passcode hashing for the app lock.
 *
 * The passcode itself is never stored — only a salted, repeated SHA-256 hash.
 * SHA-256 is implemented here (instead of crypto.subtle) because crypto.subtle
 * only exists on HTTPS pages, and the app is also opened over plain http:// on
 * the local network during development.
 *
 * Note: the lock protects against someone casually opening the app on your
 * device. It is not encryption: the notes themselves stay readable to anyone
 * with technical access to this browser's storage.
 */

export const PASSCODE_MIN = 4;
export const PASSCODE_MAX = 8;
const ROUNDS = 2000;

export function isValidPasscode(pin: string): boolean {
  return /^\d+$/.test(pin) && pin.length >= PASSCODE_MIN && pin.length <= PASSCODE_MAX;
}

export function createSalt(): string {
  const bytes = new Uint8Array(16);
  const c = globalThis.crypto as Crypto | undefined;
  if (c?.getRandomValues) c.getRandomValues(bytes);
  else for (let i = 0; i < bytes.length; i++) bytes[i] = Math.floor(Math.random() * 256);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

export function hashPasscode(pin: string, salt: string): string {
  let h = sha256Hex(`${salt}:${pin}`);
  for (let i = 1; i < ROUNDS; i++) h = sha256Hex(h + salt);
  return h;
}

export function verifyPasscode(pin: string, salt: string, expectedHash: string): boolean {
  const actual = hashPasscode(pin, salt);
  // Compare every character so the time taken doesn't depend on where they differ.
  let diff = actual.length ^ expectedHash.length;
  for (let i = 0; i < actual.length && i < expectedHash.length; i++) {
    diff |= actual.charCodeAt(i) ^ expectedHash.charCodeAt(i);
  }
  return diff === 0;
}

